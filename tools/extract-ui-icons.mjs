// One-shot extractor for the checked-in UI icon assets. The reference checkout
// is optional developer input supplied through SHUTU_REFERENCE_ROOT; normal
// build and runtime use only the generated internal/webserver/static/icons.js.
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

if (!process.env.SHUTU_REFERENCE_ROOT) {
  throw new Error('SHUTU_REFERENCE_ROOT is required only to regenerate checked-in icons')
}
const scriptDir = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(scriptDir, '..')
const root = resolve(process.env.SHUTU_REFERENCE_ROOT, 'packages/client/ui-primitives/src')
const out = resolve(repoRoot, 'internal/webserver/static/icons.js')

// Icons used by the sidebar / workspace grouping plus the brand mark and
// settings gear. Names identify the source UI primitive, not a project owner.
const WANT = new Set([
  'FishLogo',
  'IconPanelLeftOutline16',
  'IconNewChatOutline16',
  'IconSearchOutline16',
  'IconCloseFill14',
  'IconPersonalizationOutline16',
  'IconProjectAddOutline16',
  'IconFolderClose16',
  'IconFolderOpen16',
  'IconTriangleRightFill14',
  'IconEllipsisOutline16',
  'IconPlusOutline16',
  'IconEditOutline16',
  'IconTrashOutline16',
  'IconBranchOutline16',
  'IconArchiveOutline20',
  'IconSettingsOutline16',
])

const indexSrc = readFileSync(resolve(root, 'icons/index.tsx'), 'utf8')
const brandSrc = readFileSync(resolve(root, 'FishLogo.tsx'), 'utf8')

function jsxAttrsToHtml(svg) {
  return svg
    .replace(/\s(width|height|className)=\{[^}]*\}/g, '')
    .replace(/strokeWidth/g, 'stroke-width')
    .replace(/strokeLinecap/g, 'stroke-linecap')
    .replace(/strokeLinejoin/g, 'stroke-linejoin')
    .replace(/fillRule/g, 'fill-rule')
    .replace(/clipRule/g, 'clip-rule')
    .replace(/\s*\/>\s*$/m, ' />')
}

function extractSvg(src, name) {
  const declarationKind = name === 'FishLogo' ? 'function' : 'const'
  const head = src.indexOf(`export ${declarationKind} ${name}`)
  if (head === -1) throw new Error(`icon not found: ${name}`)
  const open = src.indexOf('<svg', head)
  const close = src.indexOf('</svg>', open) + '</svg>'.length
  return src.slice(open, close)
}

const icons = {}
for (const name of WANT) {
  const source = name === 'FishLogo' ? brandSrc : indexSrc
  const svg = extractSvg(source, name)
  const cleaned = jsxAttrsToHtml(svg)
    .replace(/\s+/g, ' ')
    .trim()
  const key = name.replace(/^Icon/, '').replace(/Outline\d+$|Fill\d+$/i, '').toLowerCase() || 'brand'
  icons[key] = cleaned
}

const body = `/* Checked-in UI icon assets generated by tools/extract-ui-icons.mjs.
   Each entry is a complete <svg>; sizing rides CSS via viewBox. */
const PA_ICONS = ${JSON.stringify(icons, null, 2).replace(/"((?:\\"|[^"])*)"/g, "'$1'")};
`
writeFileSync(out, body)
console.log('wrote', out, Object.keys(icons).length, 'icons:', Object.keys(icons).join(', '))
